import { expect, test } from '@playwright/test'
import { expectAutomaticallyAccessible } from './accessibility'

test('new company imports a settled receipt without duplicating cash and reports statement balances', async ({ page }) => {
  test.skip(
    process.env.FLOWPAY_E2E_ALLOW_WRITES !== 'true',
    'This journey writes financial data and runs only against an isolated E2E database.',
  )

  const id = crypto.randomUUID()
  const today = new Intl.DateTimeFormat('en-CA', {
    timeZone: 'America/Sao_Paulo',
    year: 'numeric',
    month: '2-digit',
    day: '2-digit',
  }).format(new Date())
  const dueDateValue = new Date(`${today}T12:00:00Z`)
  dueDateValue.setUTCDate(dueDateValue.getUTCDate() + 10)
  const dueDate = dueDateValue.toISOString().slice(0, 10)
  const openingDateValue = new Date(`${today}T12:00:00Z`)
  openingDateValue.setUTCDate(openingDateValue.getUTCDate() - 1)
  const openingDate = openingDateValue.toISOString().slice(0, 10)
  const closingDateValue = new Date(`${today}T12:00:00Z`)
  closingDateValue.setUTCDate(closingDateValue.getUTCDate() + 1)
  const closingDate = closingDateValue.toISOString().slice(0, 10)

  await page.goto('/')
  await page.getByLabel('Nome da empresa').fill(`E2E ${id}`)
  await page.getByLabel('E-mail').fill(`e2e-${id}@flowpay.local`)
  await page.getByLabel('Senha').fill(`FlowPay-E2E-${id}!`)
  await page.getByRole('button', { name: 'Criar empresa', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Visão geral' })).toBeVisible()

  await page.getByRole('button', { name: 'Contatos', exact: true }).click()
  await page.getByRole('button', { name: /Novo contato|Cadastrar primeiro contato/ }).click()
  const contactForm = page.locator('form').filter({ has: page.getByLabel('Nome', { exact: true }) })
  await contactForm.getByLabel('Nome', { exact: true }).fill(`Cliente ${id}`)
  await contactForm.getByLabel('Cliente', { exact: true }).check()
  await contactForm.getByLabel('Fornecedor', { exact: true }).check()
  await contactForm.getByRole('button', { name: 'Cadastrar contato', exact: true }).click()
  await expect(page.getByRole('heading', { name: `Cliente ${id}` })).toBeVisible()

  await page.getByRole('button', { name: 'Contas financeiras', exact: true }).click()
  await page.getByRole('button', { name: /Nova conta|Cadastrar primeira conta/ }).click()
  const accountForm = page.locator('form').filter({ has: page.getByLabel('Nome da conta') })
  await accountForm.getByLabel('Nome da conta').fill('Conta E2E')
  await accountForm.locator('[name="type"]').selectOption('BANK')
  await accountForm.getByLabel('Saldo inicial em reais').fill('1.000,00')
  await accountForm.getByLabel('Data do saldo inicial').fill(today)
  await accountForm.getByRole('button', { name: 'Salvar conta', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Conta E2E' })).toBeVisible()
  await expect(page.getByText('R$ 1.000,00', { exact: true })).toBeVisible()

  await page.getByRole('button', { name: 'Categorias', exact: true }).click()
  await page.getByRole('button', { name: /Nova categoria|Criar primeira categoria/ }).click()
  const categoryForm = page.locator('form').filter({ has: page.getByLabel('Nome', { exact: true }) })
  await categoryForm.getByLabel('Nome', { exact: true }).fill(`Receita ${id}`)
  await categoryForm.locator('[name="direction"]').selectOption('INFLOW')
  await categoryForm.getByRole('button', { name: 'Salvar categoria', exact: true }).click()
  await expect(page.getByText(`Receita ${id}`, { exact: true })).toBeVisible()

  await page.getByRole('button', { name: /Nova categoria|Criar primeira categoria/ }).click()
  const expenseCategoryForm = page.locator('form').filter({ has: page.getByLabel('Nome', { exact: true }) })
  await expenseCategoryForm.getByLabel('Nome', { exact: true }).fill(`Despesa ${id}`)
  await expenseCategoryForm.locator('[name="direction"]').selectOption('OUTFLOW')
  await expenseCategoryForm.getByRole('button', { name: 'Salvar categoria', exact: true }).click()
  await expect(page.getByText(`Despesa ${id}`, { exact: true })).toBeVisible()

  await page.getByRole('button', { name: 'A receber', exact: true }).click()
  await page.getByRole('button', { name: /Novo t|Cadastrar primeiro t/ }).click()
  const titleForm = page.locator('form').filter({ has: page.locator('[name="description"]') })
  await titleForm.locator('[name="description"]').fill(`Servico ${id}`)
  await titleForm.locator('[name="contactId"]').selectOption({ label: `Cliente ${id}` })
  await titleForm.locator('[name="categoryId"]').selectOption({ label: `Receita ${id}` })
  await titleForm.locator('[name="amount"]').fill('1.234,56')
  await titleForm.locator('[name="dueDate"]').fill(dueDate)
  await titleForm.locator('[name="plannedAccountId"]').selectOption({ label: 'Conta E2E' })
  await titleForm.locator('button[type="submit"]').click()
  const title = page.locator('article').filter({ has: page.getByRole('heading', { name: `Servico ${id}` }) })
  await expect(title).toBeVisible()
  await expect(title).toContainText('R$ 1.234,56 em aberto')

  await title.getByRole('button', { name: 'Registrar recebimento', exact: true }).click()
  const settlementForm = title.locator('form')
  await settlementForm.getByLabel('Valor em reais').fill('200,00')
  await settlementForm.getByLabel('Conta').selectOption({ label: 'Conta E2E' })
  await settlementForm.getByLabel('Data realizada').fill(today)
  await settlementForm.getByRole('button', { name: 'Confirmar recebimento', exact: true }).click()

  await expect(title).toContainText('R$ 1.034,56 em aberto')
  await page.reload()
  await page.getByRole('button', { name: 'A receber', exact: true }).click()
  const persistedTitle = page.locator('article').filter({ has: page.getByRole('heading', { name: `Servico ${id}` }) })
  await expect(persistedTitle).toContainText('R$ 1.034,56 em aberto')
  await expect(persistedTitle).toContainText('Parcialmente pago')

  await page.getByRole('button', { name: 'A pagar', exact: true }).click()
  await page.getByRole('button', { name: /Novo título|Cadastrar primeiro título/ }).click()
  const payableForm = page.locator('form').filter({ has: page.locator('[name="description"]') })
  await payableForm.locator('[name="description"]').fill(`Despesa ${id}`)
  await payableForm.locator('[name="contactId"]').selectOption({ label: `Cliente ${id}` })
  await payableForm.locator('[name="categoryId"]').selectOption({ label: `Despesa ${id}` })
  await payableForm.locator('[name="amount"]').fill('50,00')
  await payableForm.locator('[name="dueDate"]').fill(dueDate)
  await payableForm.locator('[name="plannedAccountId"]').selectOption({ label: 'Conta E2E' })
  await payableForm.locator('button[type="submit"]').click()
  const payable = page.locator('article').filter({ has: page.getByRole('heading', { name: `Despesa ${id}` }) })
  await expect(payable).toContainText('R$ 50,00 em aberto')
  await payable.getByRole('button', { name: 'Registrar pagamento', exact: true }).click()
  const paymentForm = payable.locator('form')
  await paymentForm.getByLabel('Valor em reais').fill('50,00')
  await paymentForm.getByLabel('Conta').selectOption({ label: 'Conta E2E' })
  await paymentForm.getByLabel('Data realizada').fill(today)
  await paymentForm.getByRole('button', { name: 'Confirmar pagamento', exact: true }).click()
  await expect(payable).toContainText('Quitado')
  await expectAutomaticallyAccessible(page, 'payables and payment')

  await page.getByRole('button', { name: 'Contas financeiras', exact: true }).click()
  const persistedAccount = page.locator('article').filter({ has: page.getByRole('heading', { name: 'Conta E2E' }) })
  await expect(persistedAccount).toContainText('R$ 1.150,00')

  await page.getByRole('button', { name: 'Extratos', exact: true }).click()
  await page.getByLabel('Conta financeira').selectOption({ label: 'Conta E2E' })
  await page.getByRole('textbox', { name: 'Saldo de abertura', exact: true }).fill('1.000,00')
  await page.getByLabel('Data do saldo de abertura').fill(openingDate)
  await page.getByRole('textbox', { name: 'Saldo de fechamento', exact: true }).fill('1.150,00')
  await page.getByLabel('Data do saldo de fechamento').fill(closingDate)
  const [year, month, day] = today.split('-')
  const receiptLine = `${day}/${month}/${year};Recebimento: Servico ${id};200,00;ENTRADA`
  const payableLine = `${day}/${month}/${year};Pagamento: Licenca ${id};50,00;SAIDA`
  const invalidLine = `31/02/${year};Linha com data inválida ${id};15,00;ENTRADA`
  const statementCsv = `data;descricao;valor;direcao\n${receiptLine}\n${receiptLine}\n${payableLine}\n${invalidLine}\n`
  await page.getByLabel('Arquivo CSV').setInputFiles({
    name: `extrato-${id}.csv`,
    mimeType: 'text/csv',
    buffer: Buffer.from(statementCsv, 'utf-8'),
  })
  await page.getByRole('button', { name: 'Gerar prévia' }).click()
  await expect(page.getByRole('heading', { name: 'Resultado da prévia' })).toBeVisible()
  await expect(page.getByText(/2 aceitas · 1 rejeitada · 1 repetida no arquivo/)).toBeVisible()
  await page.getByRole('button', { name: 'Confirmar importação' }).click()
  await expect(page.getByRole('status')).toContainText('Arquivo e linhas salvos.')
  await expect(page.getByRole('status')).toContainText('O caixa não foi alterado.')

  await page.getByRole('button', { name: 'Ver linhas', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Linhas salvas' })).toBeVisible()
  const savedLinesSection = page.getByRole('region', { name: 'Linhas salvas', exact: true })
  const savedLinesTable = page.getByRole('region', { name: 'Tabela rolável: Linhas salvas' })
  await expect(savedLinesSection).toContainText('4 registros')
  await expect(savedLinesTable.getByRole('row')).toHaveCount(5)
  await expect(savedLinesTable).toContainText('Repetida no arquivo')
  await expect(savedLinesTable).toContainText('Use uma data válida')
  const reconciliationSummary = page.getByRole('region', { name: /Resumo da/ })
  await expect(reconciliationSummary).toBeVisible()
  await expect(reconciliationSummary).toContainText('R$ 1.150,00')
  await expect(reconciliationSummary).toContainText('R$ 200,00')
  await expect(reconciliationSummary).toContainText('R$ 50,00')
  await expect(reconciliationSummary).toContainText('2 linhas válidas')
  await expect(reconciliationSummary).toContainText('1 linha rejeitada')
  await expect(reconciliationSummary).toContainText('1 linha repetida')
  await expect(reconciliationSummary).toContainText('0 de 2 linhas têm vínculo ativo.')
  await expect(reconciliationSummary.getByRole('article').filter({ hasText: 'Diferença líquida de movimentação' })).toContainText('R$ 0,00')
  const statementBalances = page.getByRole('region', { name: 'Saldos informados no extrato' })
  const reportedBalances = statementBalances.getByRole('article')
  await expect(reportedBalances).toHaveCount(4)
  await expect(reportedBalances.nth(0)).toContainText('R$ 1.000,00')
  await expect(reportedBalances.nth(1)).toContainText('R$ 1.150,00')
  await expect(reportedBalances.nth(2)).toContainText('R$ 1.150,00')
  await expect(reportedBalances.nth(3)).toContainText('R$ 0,00')
  await expect(statementBalances).toContainText('Conferência do período: saldo de fechamento menos saldo de abertura e movimentações válidas do extrato = R$ 0,00.')
  await expectAutomaticallyAccessible(page, 'saved statement lines and reconciliation summary')
  const receiptRow = savedLinesTable.getByRole('row').filter({ hasText: `Recebimento: Servico ${id}` }).filter({ hasText: 'Aceita' })
  await receiptRow.getByRole('button', { name: 'Sugerir movimento', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Sugestões de movimento' })).toBeVisible()
  const linkCandidate = page.getByRole('button', { name: 'Vincular', exact: true })
  await expect(linkCandidate).toBeVisible()
  await linkCandidate.click()
  const matchConfirmation = page.getByRole('group', { name: 'Confirmar conciliação' })
  await expect(matchConfirmation).toContainText('O caixa não será alterado.')
  await matchConfirmation.getByRole('button', { name: 'Confirmar vínculo', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('Linha vinculada ao movimento existente.')
  await expect(page.getByRole('alert')).toContainText('O caixa não foi alterado.')
  await expect(page.getByText('Conciliada', { exact: true })).toBeVisible()
  await expect(reconciliationSummary).toContainText('1 de 2 linhas têm vínculo ativo.')
  await expectAutomaticallyAccessible(page, 'reconciled statement lines and summary')
  await page.screenshot({ path: 'test-results/reconciliation-desktop.png', fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  const reconciliationDocumentWidth = await page.evaluate(() => document.documentElement.scrollWidth)
  expect(reconciliationDocumentWidth).toBeLessThanOrEqual(390)
  await expectAutomaticallyAccessible(page, 'mobile reconciliation tables')
  await page.screenshot({ path: 'test-results/reconciliation-mobile.png', fullPage: true })
  await page.getByRole('button', { name: 'Gerar prévia' }).click()
  await expect(page.getByRole('heading', { name: 'Resultado da prévia' })).toBeVisible()
  await page.getByRole('button', { name: 'Confirmar importação' }).click()
  await expect(page.getByText(/Este arquivo já estava salvo/)).toBeVisible()
  await expect(page.getByText('1 importação', { exact: true })).toBeVisible()
  await expect(page.getByText('Conciliada', { exact: true })).toBeVisible()

  await page.getByRole('button', { name: 'Contas financeiras', exact: true }).click()
  await expect(persistedAccount).toContainText('R$ 1.150,00')

  await page.getByRole('button', { name: 'Relatório mensal', exact: true }).click()
  const monthlyReport = page.getByRole('region', { name: /Relatório mensal/ })
  await expect(monthlyReport).toBeVisible()
  await expect(monthlyReport).toContainText('Entradas realizadas')
  await expect(monthlyReport).toContainText('Saídas realizadas')
  await expect(monthlyReport).toContainText('R$ 200,00')
  await expect(monthlyReport).toContainText('R$ 50,00')
  await expectAutomaticallyAccessible(page, 'monthly report')

  await page.getByRole('button', { name: 'Extratos', exact: true }).click()
  await page.getByRole('combobox', { name: 'Conta financeira', exact: true }).selectOption({ label: 'Conta E2E' })
  await page.getByRole('textbox', { name: 'Saldo de abertura', exact: true }).fill('1.000,00')
  await page.getByRole('textbox', { name: 'Data do saldo de abertura', exact: true }).fill(openingDate)
  await page.getByRole('textbox', { name: 'Saldo de fechamento', exact: true }).fill('1.300,00')
  await page.getByRole('textbox', { name: 'Data do saldo de fechamento', exact: true }).fill(closingDate)
  const rejectedOnlyCsv = `data;descricao;valor;direcao\n31/02/${year};Somente rejeitada ${id};15,00;ENTRADA\n`
  await page.getByLabel('Arquivo CSV').setInputFiles({
    name: `somente-rejeitada-${id}.csv`,
    mimeType: 'text/csv',
    buffer: Buffer.from(rejectedOnlyCsv, 'utf-8'),
  })
  await page.getByRole('button', { name: 'Gerar prévia' }).click()
  await expect(page.getByRole('heading', { name: 'Resultado da prévia' })).toBeVisible()
  await expect(page.getByText(/0 aceitas · 1 rejeitada · 0 repetidas no arquivo/)).toBeVisible()
  await page.getByRole('button', { name: 'Confirmar importação' }).click()
  await expect(page.getByRole('status')).toContainText('Arquivo e linhas salvos.')
  await expect(page.getByRole('status')).toContainText('O caixa não foi alterado.')

  const statementHistory = page.getByRole('region', { name: 'Histórico de extratos', exact: true })
  await expect(statementHistory).toContainText('2 importações')
  await statementHistory.getByRole('button', { name: 'Ver linhas', exact: true }).first().click()
  const rejectedLinesSection = page.getByRole('region', { name: 'Linhas salvas', exact: true })
  const rejectedLinesTable = page.getByRole('region', { name: 'Tabela rolável: Linhas salvas' })
  await expect(rejectedLinesSection).toContainText('1 registro')
  await expect(rejectedLinesTable).toContainText('Use uma data válida')
  const rejectedLine = rejectedLinesTable.getByRole('row').filter({ hasText: `Somente rejeitada ${id}` })
  await expect(rejectedLine.getByRole('button')).toHaveCount(0)

  const rejectedOnlySummary = page.getByRole('region', { name: /Resumo da/ })
  await expect(rejectedOnlySummary).toContainText('0 linhas válidas')
  await expect(rejectedOnlySummary).toContainText('1 linha rejeitada')
  await expect(rejectedOnlySummary).toContainText('0 de 0 linhas têm vínculo ativo.')
  const inconsistentBalances = page.getByRole('region', { name: 'Saldos informados no extrato' })
  const inconsistentBalanceCards = inconsistentBalances.getByRole('article')
  await expect(inconsistentBalanceCards.nth(0)).toContainText('R$ 1.000,00')
  await expect(inconsistentBalanceCards.nth(1)).toContainText('R$ 1.300,00')
  await expect(inconsistentBalanceCards.nth(2)).toContainText('R$ 1.150,00')
  await expect(inconsistentBalanceCards.nth(3)).toContainText('R$ 150,00')
  await expect(inconsistentBalances).toContainText('= R$ 300,00.')
})
